import {
  PostgreSqlContainer,
  StartedPostgreSqlContainer,
} from '@testcontainers/postgresql';
import { RedisContainer, StartedRedisContainer } from '@testcontainers/redis';
import { migrate } from 'drizzle-orm/node-postgres/migrator';
import { fileURLToPath } from 'node:url';
import type { TestProject } from 'vitest/node';
import { createDatabase } from '../../../src/core/database/create-database.js';

/** Folder written by `npm run db:generate` (see drizzle.config.ts). */
const MIGRATIONS_FOLDER = fileURLToPath(
  new URL('../../../migrations', import.meta.url),
);

let postgresContainer: StartedPostgreSqlContainer;
let redisContainer: StartedRedisContainer;

/**
 * Runs once before every e2e worker starts.
 * Boots a throwaway Postgres + Redis, applies the Drizzle migrations and
 * publishes the connection URLs to the tests.
 */
export async function setup(project: TestProject): Promise<void> {
  const databaseUrl = await initTestContainers(project);

  await applyMigrations(databaseUrl);
}

async function initTestContainers(project: TestProject): Promise<string> {
  postgresContainer = await new PostgreSqlContainer('postgres:17-alpine')
    .withDatabase('test')
    .start();

  redisContainer = await new RedisContainer('redis:8.6.2-alpine').start();

  const databaseUrl = postgresContainer.getConnectionUri();

  // Workers are spawned after this hook, so they inherit process.env.
  process.env.APP_DATABASE_CONNECTION_URL = databaseUrl;
  process.env.APP_REDIS_HOST = redisContainer.getHost();
  process.env.APP_REDIS_PORT = String(redisContainer.getPort());

  // Typed alternative for tests that call inject('databaseUrl').
  project.provide('databaseUrl', databaseUrl);

  return databaseUrl;
}

/** Applies the SQL migrations generated by drizzle-kit to the fresh database. */
async function applyMigrations(databaseUrl: string): Promise<void> {
  const database = createDatabase(databaseUrl);

  try {
    await migrate(database, { migrationsFolder: MIGRATIONS_FOLDER });
  } finally {
    await database.$client.end();
  }
}

/** Runs once after all e2e files have finished. */
export async function teardown(): Promise<void> {
  await postgresContainer?.stop();
  await redisContainer?.stop();
}

declare module 'vitest' {
  export interface ProvidedContext {
    databaseUrl: string;
  }
}
